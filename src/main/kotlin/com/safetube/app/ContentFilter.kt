    private val SPLIT = Regex("[^\\p{L}\\p{M}\\p{N}+']+")

    private fun norm(s: String): String = s.lowercase().replace("\u200c", "").replace("\u200d", "")
    private fun toks(s: String): List<String> = norm(s).split(SPLIT).filter { it.isNotEmpty() }

    private fun bnHas(tok: String, term: String): Boolean {
        if (tok == term) return true
        if (!tok.startsWith(term)) return false
        return SUF.contains(tok.substring(term.length))
    }

    private fun setHas(tokens: List<String>, list: List<String>, loose: Boolean): String? {
        for (t in tokens) {
            for (w in list) {
                if (t == w) return w
                val nonAscii = w.any { it.code > 0x7f }
                if (nonAscii && t.length > w.length) {
                    val hit = if (loose) (t.startsWith(w) && t.length - w.length <= 5) else bnHas(t, w)
                    if (hit) return w
                }
            }
        }
        return null
    }

    private fun phraseHas(text: String, list: List<String>): String? = list.firstOrNull { text.contains(it) }

    /** শিরোনাম বা সার্চের লেখা খারাপ কি না (কঠোর) */
    fun isBad(text: String): Boolean {
        val n = norm(text)
        val tk = toks(text)
        if (n.contains("18+") || n.contains("xxx")) return true
        if (setHas(tk, STRONG, false) != null) return true
        val weak = setHas(tk, WEAK, false) ?: phraseHas(n, WEAK_PHRASES)
        if (weak != null) {
            val ruled = setHas(tk, RULING, true)
            if (ruled == null) return true
        }
        return false
    }

    /** শুধু সবচেয়ে খারাপ শব্দ ধরে — ভিডিওর বিবরণের জন্য (সঙ্গীত/সিনেমা শব্দে আটকাবে না) */
    fun isStrongBad(text: String): Boolean {
        val n = norm(text)
        if (n.contains("18+") || n.contains("xxx")) return true
        return setHas(toks(text), STRONG, false) != null
    }

