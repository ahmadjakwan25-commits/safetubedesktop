    private fun matches(t: String, w: String, loose: Boolean): Boolean {
        if (t == w) return true
        val nonAscii = w.any { it.code > 0x7f }
        if (nonAscii && t.length > w.length) {
            return if (loose) (t.startsWith(w) && t.length - w.length <= 5) else bnHas(t, w)
        }
        return false
    }

    private fun countHits(tk: List<String>, list: List<String>, loose: Boolean): Int =
        list.count { w -> tk.any { t -> matches(t, w, loose) } }

    fun topicScore(text: String): Int = countHits(toks(text), TOPIC, true)

    /** লেখায় ইসলামিক শব্দের কয়টা আলাদা শব্দ আছে (বেশি = বেশি নিশ্চিত) */
    fun islamicScore(text: String): Int {
        val tk = toks(text)
        return countHits(tk, ISL, true) + countHits(tk, ISL_EXTRA, true)
    }

    /**
     * শিরোনাম + চ্যানেলের নামের স্কোর: ইসলামিক শব্দ যোগ, বিনোদনের শব্দ বিয়োগ।
     * সবচেয়ে খারাপ শব্দ থাকলে -99। ১ বা তার বেশি হলে চলবে।
     */
    fun textScore(text: String): Int {
        val n = norm(text)
        val tk = toks(text)
        if (n.contains("18+") || n.contains("xxx")) return -99
        if (setHas(tk, STRONG, false) != null) return -99
        var weak = countHits(tk, WEAK, false) + WEAK_PHRASES.count { n.contains(it) }
        if (weak > 0 && setHas(tk, RULING, true) != null) weak = 0
        val topics = if (weak == 0) topicScore(text) else 0
        return islamicScore(text) + topics - weak
    }
